def _clean(text: str) -> str:
    text = text.replace("\xa0", " ")
    text = re.sub(r"[ \t]+", " ", text)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip()


def chunk_guideline_text(raw: str, max_chars: int = 900, overlap: int = 120) -> list[dict[str, Any]]:
    """Режет полный текст КР на чанки с page-метками."""
    pages = re.split(r"===== PAGE (\d+) =====", raw)
    chunks: list[dict[str, Any]] = []
    # pages[0] may be empty prefix; then pairs (num, text)
    i = 1
    while i + 1 < len(pages):
        page_no = pages[i]
        body = _clean(pages[i + 1])
        i += 2
        if len(body) < 80:
            continue
        # skip mostly English title pages early
        start = 0
        while start < len(body):
            end = min(len(body), start + max_chars)
            if end < len(body):
                cut = body.rfind(". ", start, end)
                if cut > start + 200:
                    end = cut + 1
            piece = body[start:end].strip()
            if len(piece) >= 120:
                section = _guess_section(piece)
                cid = f"p{page_no}_{len(chunks):04d}"
                chunks.append(
                    {
                        "id": cid,
                        "section": section,
                        "page": int(page_no),
                        "source": "КР АГ у взрослых 2024 (РКО), ID 62_3",
                        "text": piece,
                    }
                )
            if end >= len(body):
                break
            start = max(end - overlap, start + 1)
    return chunks


def _guess_section(text: str) -> str:
    low = text.lower()
    for pattern, name in SECTION_HINTS:
        if re.search(pattern.lower(), low):
            return name
    # first line heuristic
    first = text.split("\n", 1)[0][:80]
    return first if len(first) > 20 else "КР АГ 2024"


