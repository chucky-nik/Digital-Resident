def save_chunks(chunks: list[dict[str, Any]], path: Path | None = None) -> Path:
    path = path or settings()["chunks_json"]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(chunks, ensure_ascii=False, indent=2), encoding="utf-8")
    return path


def load_or_build_chunks(include_full_text: bool = True, max_full: int = 180) -> list[dict[str, Any]]:
    curated = build_curated_chunks()
    if not include_full_text:
        return curated
    txt_path: Path = settings()["guideline_txt"]
    if not txt_path.exists():
        return curated
    raw = txt_path.read_text(encoding="utf-8", errors="ignore")
    full = chunk_guideline_text(raw)
    # keep curated first, then sample/limit full chunks focusing on treatment pages
    treatment = [c for c in full if 18 <= c.get("page", 0) <= 40]
    other = [c for c in full if c not in treatment]
    merged = curated + treatment[:80] + other[:20]
    # dedupe by id
    seen = set()
    out = []
    for c in merged:
        if c["id"] in seen:
            continue
        seen.add(c["id"])
        out.append(c)
    return out
